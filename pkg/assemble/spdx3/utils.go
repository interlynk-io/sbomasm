// genPackageListWithRoot merges packages with optional root package info for ID preservation.
func genPackageListWithRoot(ms *merge, rootPkgInfo *rootPackageInfo) ([]*spdx3model.Package, map[string]string, error) {
	var pkgs []*spdx3model.Package
	mapper := make(map[string]string)
	seen := make(map[string]string)

	for _, doc := range ms.in {
		for _, pkg := range doc.Packages {
			if pkg == nil {
				continue
			}

			key := fmt.Sprintf("%s-%s", strings.ToLower(pkg.Name), strings.ToLower(pkg.PackageVersion))

			// Check if this is the root package from the primary SBOM
			isRootPkg := rootPkgInfo != nil && pkg.SpdxID == rootPkgInfo.SpdxID

			// If already seen, map the old spdxId to the new spdxId
			if newID, exists := seen[key]; exists {
				mapper[pkg.SpdxID] = newID
				continue
			}

			clone := &spdx3model.Package{}
			if err := cloneElement(pkg, clone); err != nil {
				return nil, nil, err
			}

			var newSpdxID string
			if isRootPkg {
				newSpdxID = fmt.Sprintf("https://interlynk.io/package/root-%s", ms.rootPackageID)
			} else {
				newSpdxID = fmt.Sprintf("https://interlynk.io/package/%s-%s", sanitizeForID(pkg.Name), uuid.New().String())
			}

			mapper[pkg.SpdxID] = newSpdxID
			seen[key] = newSpdxID
			clone.SpdxID = newSpdxID

			// Reset creation info to share the output document's
			if ms.out != nil && ms.out.CreationInfo != nil {
				clone.CreationInfo = *ms.out.CreationInfo
			}

			pkgs = append(pkgs, clone)
		}
	}

	return pkgs, mapper, nil
}

// genFileList merges files from all input documents.
func genFileList(ms *merge) ([]*spdx3model.File, map[string]string, error) {
	var files []*spdx3model.File
	mapper := make(map[string]string)

	for _, doc := range ms.in {
		for _, file := range doc.Files {
			if file == nil {
				continue
			}

			clone := &spdx3model.File{}
			if err := cloneElement(file, clone); err != nil {
				return nil, nil, err
			}

			newSpdxID := fmt.Sprintf("https://interlynk.io/file/%s-%s", sanitizeForID(file.Name), uuid.New().String())
			mapper[file.SpdxID] = newSpdxID
			clone.SpdxID = newSpdxID

			if ms.out != nil && ms.out.CreationInfo != nil {
				clone.CreationInfo = *ms.out.CreationInfo
			}

			files = append(files, clone)
		}
	}

	return files, mapper, nil
}

// genRelationshipList merges relationships from all input documents, rewriting From/To references.
func genRelationshipList(ms *merge, pkgMapper map[string]string, fileMapper map[string]string) ([]*spdx3model.Relationship, error) {
	var relationships []*spdx3model.Relationship
	seen := make(map[string]bool)

	for _, doc := range ms.in {
		for _, rel := range doc.Relationships {
			if rel == nil {
				continue
			}

			// Skip DESCRIBES relationships from input SBOMs
			if rel.RelationshipType == spdx3model.RelationshipTypeDescribes {
				continue
			}

			clone := &spdx3model.Relationship{}
			if err := cloneElement(rel, clone); err != nil {
				return nil, err
			}

			// Rewrite From reference
			if newID, ok := pkgMapper[rel.From.SpdxID]; ok {
				clone.From.SpdxID = newID
			} else if newID, ok := fileMapper[rel.From.SpdxID]; ok {
				clone.From.SpdxID = newID
			}

			// Rewrite To references
			for i := range clone.To {
				if newID, ok := pkgMapper[clone.To[i].SpdxID]; ok {
					clone.To[i].SpdxID = newID
				} else if newID, ok := fileMapper[clone.To[i].SpdxID]; ok {
					clone.To[i].SpdxID = newID
				}
			}

			// Generate new spdxId for the relationship
			clone.SpdxID = fmt.Sprintf("https://interlynk.io/relationship/%s-%s-%s",
				string(clone.RelationshipType), sanitizeForID(clone.From.SpdxID), uuid.New().String())

			// Deduplicate relationships by content
			dedupKey := fmt.Sprintf("%s:%s:%s", clone.From.SpdxID, clone.RelationshipType, elementsKey(clone.To))
			if seen[dedupKey] {
				continue
			}
			seen[dedupKey] = true

			if ms.out != nil && ms.out.CreationInfo != nil {
				clone.CreationInfo = *ms.out.CreationInfo
			}

			relationships = append(relationships, clone)
		}
	}

	return relationships, nil
}

// elementsKey generates a deduplication key for a slice of elements.
func elementsKey(els []spdx3model.Element) string {
	var ids []string
	for _, el := range els {
		ids = append(ids, el.SpdxID)
	}
	return strings.Join(ids, ",")
}

// genAgentList merges agents (Organizations, Persons, Tools) from all input documents.
func genAgentList(ms *merge) (*agentCollection, error) {
	agents := &agentCollection{}
	seenOrgs := make(map[string]bool)
	seenPersons := make(map[string]bool)
	seenTools := make(map[string]bool)

	for _, doc := range ms.in {
		for _, org := range doc.Organizations {
			if org == nil {
				continue
			}
			key := org.Name
			if seenOrgs[key] {
				continue
			}
			seenOrgs[key] = true
			clone := &spdx3model.Organization{}
			if err := cloneElement(org, clone); err != nil {
				return nil, err
			}
			clone.SpdxID = fmt.Sprintf("https://interlynk.io/organization/%s-%s", sanitizeForID(org.Name), uuid.New().String())
			if ms.out != nil && ms.out.CreationInfo != nil {
				clone.CreationInfo = *ms.out.CreationInfo
			}
			agents.Organizations = append(agents.Organizations, clone)
		}

		for _, person := range doc.Persons {
			if person == nil {
				continue
			}
			key := person.Name
			if seenPersons[key] {
				continue
			}
			seenPersons[key] = true
			clone := &spdx3model.Person{}
			if err := cloneElement(person, clone); err != nil {
				return nil, err
			}
			clone.SpdxID = fmt.Sprintf("https://interlynk.io/person/%s-%s", sanitizeForID(person.Name), uuid.New().String())
			if ms.out != nil && ms.out.CreationInfo != nil {
				clone.CreationInfo = *ms.out.CreationInfo
			}
			agents.Persons = append(agents.Persons, clone)
		}

		for _, tool := range doc.Tools {
			if tool == nil {
				continue
			}
			key := tool.Name
			if seenTools[key] {
				continue
			}
			seenTools[key] = true
			clone := &spdx3model.Tool{}
			if err := cloneElement(tool, clone); err != nil {
				return nil, err
			}
			clone.SpdxID = fmt.Sprintf("https://interlynk.io/tool/%s-%s", sanitizeForID(tool.Name), uuid.New().String())
			if ms.out != nil && ms.out.CreationInfo != nil {
				clone.CreationInfo = *ms.out.CreationInfo
			}
			agents.Tools = append(agents.Tools, clone)
		}
	}

	return agents, nil
}

// genHierarchicalContains generates CONTAINS relationships between each input SBOM's
// primary package and its non-primary packages.
func genHierarchicalContains(ms *merge, pkgMapper map[string]string, ci *spdx3model.CreationInfo) []*spdx3model.Relationship {
	log := logger.FromContext(*ms.settings.Ctx)
	var newRels []*spdx3model.Relationship
	seenPairs := make(map[string]bool)

	if ci == nil {
		return newRels
	}

	for _, doc := range ms.in {
		if doc.SpdxDocument == nil || len(doc.SpdxDocument.RootElement) == 0 {
			continue
		}

		primaryID := doc.SpdxDocument.RootElement[0].SpdxID
		mappedPrimaryID, found := pkgMapper[primaryID]
		if !found {
			log.Warnf("could not find mapped primary package %s", primaryID)
			continue
		}

		for _, pkg := range doc.Packages {
			if pkg == nil || pkg.SpdxID == primaryID {
				continue
			}

			childID, found := pkgMapper[pkg.SpdxID]
			if !found {
				continue
			}

			pairKey := fmt.Sprintf("%s->%s", mappedPrimaryID, childID)
			if seenPairs[pairKey] {
				continue
			}
			seenPairs[pairKey] = true

			newRels = append(newRels, &spdx3model.Relationship{
				Element: spdx3model.Element{
					SpdxID:       fmt.Sprintf("https://interlynk.io/relationship/contains-%s", uuid.New().String()),
					Name:         "contains relationship",
					CreationInfo: *ci,
				},
				From:             spdx3model.Element{SpdxID: mappedPrimaryID},
				To:               []spdx3model.Element{{SpdxID: childID}},
				RelationshipType: spdx3model.RelationshipTypeContains,
			})
		}
	}

	log.Debugf("generated %d CONTAINS relationships for hierarchical merge", len(newRels))
	return newRels
}

func writeSBOM(doc *parse.Document, m *merge) error {
	log := logger.FromContext(*m.settings.Ctx)
	var w io.Writer
	outName := "stdout"

	if m.settings.Output.File == "" {
		w = os.Stdout
	} else {
		outName = m.settings.Output.File
		file, err := os.Create(m.settings.Output.File)
		if err != nil {
			return err
		}
		defer file.Close()
		w = file
	}

	wrapper := &sbom.SPDX3Document{Doc: doc}
	if err := sbom.WriteSBOM(w, wrapper); err != nil {
		return fmt.Errorf("failed to write SPDX 3.0 SBOM: %w", err)
	}

	log.Debugf("wrote SPDX 3.0 sbom to %s with packages:%d, files:%d, relationships:%d, orgs:%d, persons:%d, tools:%d",
		outName, len(doc.Packages), len(doc.Files), len(doc.Relationships),
		len(doc.Organizations), len(doc.Persons), len(doc.Tools))

	return nil
}

// sanitizeForID replaces characters that are problematic in URIs.
func sanitizeForID(s string) string {
	s = strings.ToLower(s)
	s = strings.ReplaceAll(s, " ", "-")
	s = strings.ReplaceAll(s, "/", "-")
	s = strings.ReplaceAll(s, "\\", "-")
	s = strings.ReplaceAll(s, ".", "-")
	s = strings.ReplaceAll(s, "_", "-")
	return s
}
