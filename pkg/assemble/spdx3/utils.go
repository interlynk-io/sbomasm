func findPrimaryAndSecondaryIndices(docCount int) (int, []int) {
	primaryIdx := 0
	var secondaryIdxs []int
	for i := 1; i < docCount; i++ {
		secondaryIdxs = append(secondaryIdxs, i)
	}
	return primaryIdx, secondaryIdxs
}

// getRootElementPkgID returns the spdxId of the first rootElement package.
func getRootElementPkgID(doc *parse.Document) string {
	if doc.SpdxDocument == nil || len(doc.SpdxDocument.RootElement) == 0 {
		return ""
	}
	return doc.SpdxDocument.RootElement[0].SpdxID
}

// extractPrimaryPackage finds and clones the package referenced by the primary SBOM's RootElement.
func extractPrimaryPackage(doc *parse.Document) (*spdx3model.Package, error) {
	primaryPkgID := getRootElementPkgID(doc)
	if primaryPkgID == "" {
		return nil, fmt.Errorf("primary SBOM has no rootElement")
	}

	for _, pkg := range doc.Packages {
		if pkg.SpdxID == primaryPkgID {
			clone := &spdx3model.Package{}
			if err := cloneElement(pkg, clone); err != nil {
				return nil, err
			}
			return clone, nil
		}
	}

	return nil, fmt.Errorf("primary package %s not found in primary SBOM", primaryPkgID)
}

// initOutDocFromPrimarySBOM initializes the output document metadata from the primary SBOM.
func initOutDocFromPrimarySBOM(m *merge, primaryDoc *parse.Document) (*parse.Document, error) {
	doc := &parse.Document{}

	spdxDoc := &spdx3model.SpdxDocument{}
	if primaryDoc.SpdxDocument != nil {
		spdxDoc.SpdxID = primaryDoc.SpdxDocument.SpdxID
		spdxDoc.Name = primaryDoc.SpdxDocument.Name
		spdxDoc.ProfileConformance = primaryDoc.SpdxDocument.ProfileConformance
	} else {
		spdxDoc.SpdxID = composeNamespace(m.settings.App.Name)
		spdxDoc.Name = m.settings.App.Name
	}

	doc.SpdxDocument = spdxDoc
	return doc, nil
}

// initCreationInfoFromPrimarySBOM initializes creation info preserving the primary SBOM's creators.
func initCreationInfoFromPrimarySBOM(m *merge, primaryDoc *parse.Document) (*spdx3model.CreationInfo, error) {
	ci := spdx3model.CreationInfo{}

	// Set spec version and update timestamp
	ci.SpecVersion = spdx3model.SpecVersion
	ci.Created = utcNowTime()

	// Generate comment referencing all merged documents
	var docNames []string
	for _, inDoc := range m.in {
		if inDoc.SpdxDocument != nil {
			docNames = append(docNames, inDoc.SpdxDocument.Name)
		}
	}

	sbomasmComment := fmt.Sprintf("Generated by sbomasm (%s) using %s",
		version.GetVersionInfo().GitVersion, strings.Join(docNames, ", "))

	if primaryDoc.SpdxDocument != nil {
		primaryCI := &primaryDoc.SpdxDocument.CreationInfo
		if primaryCI.Comment != "" {
			ci.Comment = primaryCI.Comment + "\n" + sbomasmComment
		} else {
			ci.Comment = sbomasmComment
		}
	} else {
		ci.Comment = sbomasmComment
	}

	// Preserve primary's creators (Agents only)
	var creators []spdx3model.Agent
	if primaryDoc.CreationInfo != nil {
		for _, agent := range primaryDoc.CreationInfo.CreatedBy {
			if agent.Name == "" {
				continue
			}
			creators = append(creators, agent)
		}
	}

	// Deduplicate creators by name
	seen := make(map[string]bool)
	var finalCreators []spdx3model.Agent
	for _, c := range creators {
		if _, ok := seen[c.Name]; ok {
			continue
		}
		seen[c.Name] = true
		finalCreators = append(finalCreators, c)
	}

	ci.CreatedBy = finalCreators

	// Build createdUsing (Tools only)
	tool := &spdx3model.Tool{}
	tool.SpdxID = fmt.Sprintf("https://interlynk.io/tool/sbomasm-%s", version.GetVersionInfo().GitVersion)
	tool.Name = "sbomasm"
	ci.CreatedUsing = []spdx3model.Tool{*tool}

	return &ci, nil
}

// getSecondaryDescribedPkgs returns the described packages from secondary SBOMs only.
func getSecondaryDescribedPkgs(docs []*parse.Document, secondaryIdxs []int) []string {
	var pkgs []string
	for _, idx := range secondaryIdxs {
		doc := docs[idx]
		if doc.SpdxDocument == nil || len(doc.SpdxDocument.RootElement) == 0 {
			continue
		}
		rootID := doc.SpdxDocument.RootElement[0].SpdxID
		if rootID != "" {
			pkgs = append(pkgs, rootID)
		}
	}
	return pkgs
}

