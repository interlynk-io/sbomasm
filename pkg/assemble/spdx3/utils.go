// loadBom parses an SPDX 3.0 JSON-LD file at path into a *parse.Document.
func loadBom(ctx context.Context, path string) (*parse.Document, error) {
	log := logger.FromContext(ctx)

	sbomDoc, err := sbom.Parser(ctx, path)
	if err != nil {
		return nil, err
	}

	spdx3Doc, ok := sbomDoc.(*sbom.SPDX3Document)
	if !ok {
		return nil, fmt.Errorf("expected SPDX 3.0 document, got %T", sbomDoc)
	}

	log.Debugf("loading SPDX 3.0 bom: %s", path)
	return spdx3Doc.Doc, nil
}

func utcNowTime() time.Time {
	return time.Now().UTC()
}

func cloneElement(src interface{}, dst interface{}) error {
	b, err := json.Marshal(src)
	if err != nil {
		return err
	}
	return json.Unmarshal(b, dst)
}

// composeNamespace generates a unique namespace for the output document.
func composeNamespace(docName string) string {
	u := uuid.New().String()
	return fmt.Sprintf("https://interlynk.io/spdxdocs/%s/%s", docName, u)
}

// genSpdxDocumentMetadata creates a new SpdxDocument for the merged output.
func genSpdxDocumentMetadata(ms *merge) (*parse.Document, error) {
	if ms == nil {
		return nil, fmt.Errorf("settings is required")
	}

	doc := &parse.Document{}

	spdxDoc := &spdx3model.SpdxDocument{}
	spdxDoc.SpdxID = composeNamespace(ms.settings.App.Name)
	spdxDoc.Name = ms.settings.App.Name

	// Set profile conformance
	spdxDoc.ProfileConformance = []spdx3model.ProfileIdentifierType{
		spdx3model.ProfileIdentifierTypeCore,
		spdx3model.ProfileIdentifierTypeSoftware,
	}

	doc.SpdxDocument = spdxDoc
	return doc, nil
}

// genCreationInfo creates a new CreationInfo for the merged document.
func genCreationInfo(ms *merge) (*spdx3model.CreationInfo, error) {
	ci := spdx3model.CreationInfo{}

	// Set spec version and creation time
	ci.SpecVersion = spdx3model.SpecVersion
	ci.Created = utcNowTime()

	// Build createdBy (Agents only: Persons + Organizations)
	var createdBy []spdx3model.Agent
	seenCreators := make(map[string]bool)

	// Add authors from CLI settings as Persons
	for _, author := range ms.settings.App.Authors {
		if author.Name == "" {
			continue
		}
		person := &spdx3model.Person{}
		person.SpdxID = fmt.Sprintf("https://interlynk.io/person/%s-%s", sanitizeForID(author.Name), uuid.New().String())
		person.Name = author.Name
		createdBy = append(createdBy, spdx3model.Agent{Element: person.Element})
		seenCreators[author.Name] = true
	}

	// Merge creators from input documents' CreationInfo
	for _, inDoc := range ms.in {
		if inDoc.CreationInfo == nil {
			continue
		}
		for _, agent := range inDoc.CreationInfo.CreatedBy {
			key := agent.Name
			if key == "" {
				key = agent.SpdxID
			}
			if _, exists := seenCreators[key]; !exists {
				seenCreators[key] = true
				createdBy = append(createdBy, agent)
			}
		}
	}

	ci.CreatedBy = createdBy

	// Build createdUsing (Tools only)
	tool := &spdx3model.Tool{}
	tool.SpdxID = fmt.Sprintf("https://interlynk.io/tool/sbomasm-%s", version.GetVersionInfo().GitVersion)
	tool.Name = "sbomasm"
	ci.CreatedUsing = []spdx3model.Tool{*tool}

	// Generate comment referencing all merged documents
	var docNames []string
	for _, inDoc := range ms.in {
		if inDoc.SpdxDocument != nil {
			docNames = append(docNames, inDoc.SpdxDocument.Name)
		}
	}
	if len(docNames) > 0 {
		ci.Comment = fmt.Sprintf("Generated by sbomasm (%s) using %s",
			version.GetVersionInfo().GitVersion, strings.Join(docNames, ", "))
	}

	return &ci, nil
}

// genPrimaryPackage creates a new primary Package from CLI app settings.
func genPrimaryPackage(ms *merge) (*spdx3model.Package, error) {
	pkg := &spdx3model.Package{}

	pkg.SpdxID = fmt.Sprintf("https://interlynk.io/package/root-%s", ms.rootPackageID)
	pkg.Name = ms.settings.App.Name
	pkg.PackageVersion = ms.settings.App.Version
	pkg.Description = ms.settings.App.Description
	pkg.CopyrightText = ms.settings.App.Copyright

	// Set primary purpose if valid
	if purpose, ok := spdx3_strings_to_purposes[ms.settings.App.PrimaryPurpose]; ok {
		pkg.PrimaryPurpose = spdx3model.SoftwarePurpose(purpose)
	}

	// Add supplier if provided
	if ms.settings.App.Supplier.Name != "" {
		org := &spdx3model.Organization{}
		org.SpdxID = fmt.Sprintf("https://interlynk.io/organization/%s-%s", sanitizeForID(ms.settings.App.Supplier.Name), uuid.New().String())
		org.Name = ms.settings.App.Supplier.Name
		pkg.SuppliedBy = &spdx3model.Agent{Element: org.Element}
	}

	// Add checksums if provided
	if len(ms.settings.App.Checksums) > 0 {
		for _, c := range ms.settings.App.Checksums {
			if c.Value == "" {
				continue
			}
			algo := spdx3model.HashAlgorithm(c.Algorithm)
			pkg.VerifiedUsing = append(pkg.VerifiedUsing, spdx3model.Hash{
				Algorithm: algo,
				HashValue: c.Value,
			})
		}
	}

	// Add PURL if provided
	if ms.settings.App.Purl != "" {
		pkg.ExternalIdentifier = append(pkg.ExternalIdentifier, spdx3model.ExternalIdentifier{
			ExternalIdentifierType: spdx3model.ExternalIdentifierTypePackageUrl,
			Identifier:             ms.settings.App.Purl,
		})
	}

	// Add CPE if provided
	if ms.settings.App.CPE != "" {
		cpeType := spdx3model.ExternalIdentifierTypeCpe23
		if strings.HasPrefix(ms.settings.App.CPE, "cpe:/") {
			cpeType = spdx3model.ExternalIdentifierTypeCpe22
		}
		pkg.ExternalIdentifier = append(pkg.ExternalIdentifier, spdx3model.ExternalIdentifier{
			ExternalIdentifierType: cpeType,
			Identifier:             ms.settings.App.CPE,
		})
	}

	// Set concluded license
	if ms.settings.App.License.Id != "" {
		// Will be handled via HAS_CONCLUDED_LICENSE relationship in future
	} else if ms.settings.App.License.Expression != "" {
		// Will be handled via license expression in future
	}

	return pkg, nil
}

// rootPackageInfo holds the SpdxID of the primary package from the primary SBOM.
